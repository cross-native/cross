# Regenerates the checked-in AArch64 startup (start_<set>.s) and host
# reference main (main_<set>.cpp) for one differential kernel set from its
# @ABI@ template. Both list the kernels in template order and call each with
# the same six argument triples; neither depends on the ABI that
# differential.cmake substitutes, because every kernel takes three u32
# arguments in w0-w2 and returns a u32 in w0 under both aapcs64 and x.
# Rerun it by hand only when a kernel set gains, loses, or renames a kernel,
# and check the results in.
#
# usage: generate.py <kernels.x.in> <start.s> <main.cpp>

import re
import sys

template, out_s, out_cpp = sys.argv[1:4]
names = re.findall(r"global u32 (k_\w+)\(", open(template).read())

# Six argument triples exercising zero/small, mixed, sign-boundary,
# mixed-hex, high-bit, and small-shift-amount inputs.
ARGS = [
    (0x00000001, 0x00000003, 0x00000005),
    (0x00000007, 0x00000002, 0x00000000),
    (0xffffffff, 0x80000000, 0x7fffffff),
    (0x12345678, 0x9abcdef0, 0x0000002b),
    (0x80000000, 0xffffffff, 0x00000010),
    (0x0000000f, 0x00000010, 0x00000021),
]


def move(register, value):
    lines = [f"movz {register}, #{value & 0xffff:#x}"]
    if value >> 16:
        lines.append(f"movk {register}, #{value >> 16:#x}, lsl #16")
    return lines


s = [
    '.section .text.start,"ax",@progbits', ".globl _start", ".type _start, %function",
    "_start:",
    "adrp x0, stack_top", "add x0, x0, :lo12:stack_top", "mov sp, x0",
    # Floating point at EL1, which the kernels do not use.
    "movz x0, #0x30, lsl #16", "msr cpacr_el1, x0", "isb",
]
cpp = ["#include <cstdio>", "", 'extern "C" {']
cpp += [f"unsigned {name}(unsigned, unsigned, unsigned);" for name in names]
cpp += ["}", "", "int main() {"]
for name in names:
    for (a, b, c) in ARGS:
        s += move("w0", a) + move("w1", b) + move("w2", c) + [f"bl {name}", "bl print_hex"]
        cpp.append(f'    std::printf("%08x\\n", {name}({a:#x}u, {b:#x}u, {c:#x}u)); '
                   "std::fflush(stdout);")
s += [
    # Semihosting SYS_EXIT with status 0.
    "adrp x1, exit_block", "add x1, x1, :lo12:exit_block", "movz w0, #0x18",
    "hlt #0xf000", "1:", "b 1b",
    "",
    # Prints w0 as eight hex digits and a newline on the PL011 UART of
    # QEMU's virt machine; changes x0-x3 only.
    ".type print_hex, %function", "print_hex:",
    "movz x1, #0x900, lsl #16", "movz w2, #8",
    "2:", "lsr w3, w0, #28", "cmp w3, #10", "b.cc 3f", "add w3, w3, #87", "b 4f",
    "3:", "add w3, w3, #48",
    "4:", "strb w3, [x1]", "lsl w0, w0, #4", "subs w2, w2, #1", "b.ne 2b",
    "movz w3, #10", "strb w3, [x1]", "ret",
    "",
    ".data", ".p2align 3", "exit_block:", ".xword 0x20026, 0",
]
cpp += ["    return 0;", "}"]

header_s = [
    "// Copyright (C) 2026 Cross contributors",
    "// SPDX-License-Identifier: GPL-3.0-or-later",
    "//",
    f"// Generated by generate.py from {template.split('/')[-1]} -- do not edit by hand.",
    "// Calls every kernel with six argument triples and prints each u32",
    "// result as 8 hex digits on the UART of QEMU's virt machine.",
    "",
]
header_cpp = [
    "// Copyright (C) 2026 Cross contributors",
    "// SPDX-License-Identifier: GPL-3.0-or-later",
    "//",
    f"// Generated by generate.py from {template.split('/')[-1]} -- do not edit by hand.",
    "// Host x86-64 reference: prints each u32 result as 8 hex digits, in the",
    "// same kernel/argument order as the generated AArch64 startup.",
    "",
]


def asm_line(line):
    if not line or line.startswith(".") or line.endswith(":"):
        return line
    return "\t" + line


open(out_s, "w").write("\n".join(header_s + [asm_line(line) for line in s]) + "\n")
open(out_cpp, "w").write("\n".join(header_cpp + cpp) + "\n")
print(f"{len(names)} kernels x {len(ARGS)} argument sets -> {out_s}, {out_cpp}")
